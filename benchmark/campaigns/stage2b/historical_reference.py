#!/usr/bin/env python3
"""Read-only historical reference from the verified Stage 2A archive (#110).

    python3 -I -B historical_reference.py ARCHIVE_ROOT [--check FILE]

ARCHIVE_ROOT is the extracted root directory `pre06-stage2a-campaign-v1/` of the
archive `pre06-stage2a-campaign-v1.tar.gz` (release `bench-pre06-v1`). The script
only reads it. It writes, to standard output, one TSV row per (Julia version, case):
the five repetition medians, the mean of those medians, the five input hashes and
the descriptive fields that explain how to read them.

This is historical context, not a paired experiment: the numbers describe one
declared stack (ProximalSolvers b0de3f7, ProximalBase 0.5.4) at Stage 2A and are
never a baseline for a ratio. Julia 1.10 and Julia 1.13 rows are separate strata and
are never pooled or paired.

The script verifies, and aborts (exit 2) when any check fails, never skipping:
  * the campaign identity and the case list of campaign.toml / cases.txt;
  * for each Julia version, 5 repetitions of 19 cases, every case status `ok`,
    samples = ok_samples = 100 per repetition;
  * the per-repetition metadata (harness hash, source SHA, ProximalBase version);
  * catalog fields (phase, measure, target) against campaign.toml;
  * mean of the five repetition medians equals `mean_ns` of summary.csv;
  * `worst_value` and `median_bytes` of summary.csv against the repetition rows;
  * one input hash per case when campaign.toml says `fixed`, five when `draw`.

With --check FILE the committed TSV must equal the regenerated one (exit 1 if not).
Standard library only; Python 3.11 or later (tomllib).
"""

import argparse
import csv
import io
import math
import os
import statistics
import sys
import tomllib
from decimal import Decimal

ARCHIVE_SHA256 = "1edd64330606d739acf1d7b4ba0643a4fb6a1366bad4c82393e2ba1ffdcc723e"
ARCHIVE_ASSET = "pre06-stage2a-campaign-v1.tar.gz"
CAMPAIGN_ID = "pre06-stage2a-v1"
REPETITIONS = 5
CASES = 19
SAMPLES = 100
JULIA_STRATA = ("1.10", "1.13")

COLUMNS = ("julia", "label", "id", "role", "phase", "inputs", "measure", "target",
           "rep_median_ns", "mean_of_medians_ns", "data_hash_per_rep", "distinct_hashes",
           "worst_value_max", "median_bytes", "ok_samples_total", "status")

HEADER = (
    "# Historical reference of the Stage 2A campaign pre06-stage2a-v1 (#110, Stage 2B).",
    f"# Source archive: {ARCHIVE_ASSET}, SHA-256 {ARCHIVE_SHA256} (release bench-pre06-v1).",
    "# Generated by historical_reference.py from the extracted, verified archive; "
    "never edited by hand.",
    "# Descriptive record of one declared stack (ProximalSolvers b0de3f7, ProximalBase 0.5.4). "
    "Not a paired experiment and not a baseline for a ratio.",
    "# One stratum per Julia version (1.10.13, 1.13.3); the strata are never pooled or paired.",
    "# rep_median_ns and data_hash_per_rep: repetitions 1..5 joined by ';'. "
    "inputs=fixed: one hash; inputs=draw: five hashes.",
    "# mean_of_medians_ns equals mean_ns of summary.csv; median_bytes is the summary.csv value.",
)


class Abort(Exception):
    pass


def need(condition, message):
    if not condition:
        raise Abort(message)


def read_toml(path):
    need(os.path.isfile(path), f"missing file {path}")
    with open(path, "rb") as handle:
        return tomllib.load(handle)


def read_tsv(path):
    need(os.path.isfile(path), f"missing file {path}")
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def read_csv(path):
    need(os.path.isfile(path), f"missing file {path}")
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def decimal_text(value):
    text = format(value, "f")
    return text


def load_campaign(root):
    campaign = read_toml(os.path.join(root, "campaign.toml"))
    need(campaign.get("campaign_id") == CAMPAIGN_ID, "campaign_id is not " + CAMPAIGN_ID)
    cases = campaign.get("case", [])
    need(len(cases) == CASES, f"campaign.toml lists {len(cases)} cases, expected {CASES}")
    with open(os.path.join(root, "cases.txt"), encoding="utf-8") as handle:
        ids = [line.rstrip("\n") for line in handle if line.strip()]
    need(ids == [c["id"] for c in cases], "cases.txt differs from the [[case]] ids of campaign.toml")
    labels = [c["label"] for c in cases]
    need(len(set(labels)) == CASES, "case labels are not unique")
    return campaign, cases


def load_stratum(root, campaign, cases, stratum):
    julia = campaign["julia"][stratum]["version"]
    folder = os.path.join(root, f"julia-{stratum}")
    need(os.path.isdir(folder), f"missing directory {folder}")
    by_id = {c["id"]: [] for c in cases}
    for rep in range(1, REPETITIONS + 1):
        stem = os.path.join(folder, "raw", f"julia-{julia}-rep{rep:02d}")
        meta = read_toml(stem + "-metadata.toml")
        need(meta.get("finished") is True, f"{stem}: repetition not finished")
        need(meta.get("rep") == rep, f"{stem}: metadata rep {meta.get('rep')} != {rep}")
        need(meta.get("julia") == julia, f"{stem}: Julia {meta.get('julia')} != {julia}")
        need(meta.get("cases") == CASES and meta.get("ok_cases") == CASES
             and meta.get("nonok_cases") == 0, f"{stem}: not 19 ok cases in the metadata")
        need(meta.get("harness_hash") == campaign["proximalsolvers"]["harness_hash"],
             f"{stem}: harness hash differs from campaign.toml")
        need(meta.get("proximalsolvers_sha") == campaign["proximalsolvers"]["commit"],
             f"{stem}: ProximalSolvers SHA differs from campaign.toml")
        need(meta.get("proximalbase_version") == campaign["proximalbase"]["version"],
             f"{stem}: ProximalBase version differs from campaign.toml")
        rows = read_tsv(stem + "-metrics.tsv")
        need(len(rows) == CASES, f"{stem}: {len(rows)} metric rows, expected {CASES}")
        seen = set()
        for row in rows:
            need(row["id"] in by_id, f"{stem}: unknown case {row['id']}")
            need(row["id"] not in seen, f"{stem}: duplicate case {row['id']}")
            seen.add(row["id"])
            need(int(row["rep"]) == rep, f"{stem}: {row['id']} has rep {row['rep']}")
            need(row["status"] == "ok", f"{stem}: {row['id']} status {row['status']}")
            need(int(row["samples"]) == SAMPLES and int(row["ok_samples"]) == SAMPLES,
                 f"{stem}: {row['id']} has {row['ok_samples']}/{row['samples']} ok samples")
            by_id[row["id"]].append(row)
        need(seen == set(by_id), f"{stem}: cases differ from campaign.toml")
    summary = {r["id"]: r for r in read_csv(os.path.join(folder, "summary", "summary.csv"))}
    need(set(summary) == set(by_id), f"julia-{stratum}: summary.csv cases differ from campaign.toml")
    return julia, by_id, summary


def build_rows(root):
    campaign, cases = load_campaign(root)
    out = []
    for stratum in JULIA_STRATA:
        julia, by_id, summary = load_stratum(root, campaign, cases, stratum)
        for case in cases:
            rows = by_id[case["id"]]
            reps = [int(r["rep"]) for r in rows]
            need(reps == list(range(1, REPETITIONS + 1)), f"{case['id']}: repetitions {reps}")
            for field in ("phase", "measure"):
                need(all(r[field] == case[field] for r in rows),
                     f"{case['id']}: {field} differs from campaign.toml")
            need(all(float(r["target"]) == float(case["target"]) for r in rows),
                 f"{case['id']}: target differs from campaign.toml")
            medians = [int(r["median_ns"]) for r in rows]
            hashes = [r["data_hash"] for r in rows]
            distinct = len(set(hashes))
            expected = {"fixed": 1, "draw": REPETITIONS}[case["inputs"]]
            need(distinct == expected,
                 f"{case['id']} ({julia}): {distinct} distinct hashes, inputs={case['inputs']}")
            s = summary[case["id"]]
            need(s["julia"] == julia, f"{case['id']}: summary julia {s['julia']} != {julia}")
            mean = Decimal(sum(medians)) / REPETITIONS
            need(math.isclose(float(s["mean_ns"]), float(mean), rel_tol=1e-12, abs_tol=0.0),
                 f"{case['id']} ({julia}): mean of medians {mean} != summary mean_ns {s['mean_ns']}")
            worst = max(rows, key=lambda r: float(r["worst_value"]))["worst_value"]
            need(float(worst) == float(s["worst_value"]),
                 f"{case['id']} ({julia}): worst value {worst} != summary {s['worst_value']}")
            bytes_median = statistics.median(int(r["median_bytes"]) for r in rows)
            need(float(bytes_median) == float(s["median_bytes"]),
                 f"{case['id']} ({julia}): median bytes {bytes_median} != summary {s['median_bytes']}")
            ok_total = sum(int(r["ok_samples"]) for r in rows)
            need(ok_total == REPETITIONS * SAMPLES, f"{case['id']}: {ok_total} ok samples in total")
            need(int(s["status_ok"]) == REPETITIONS and int(s["runs"]) == REPETITIONS,
                 f"{case['id']} ({julia}): summary does not count {REPETITIONS} ok runs")
            out.append((julia, case["label"], case["id"], case["role"], case["phase"],
                        case["inputs"], case["measure"], repr(float(case["target"])),
                        ";".join(str(m) for m in medians), decimal_text(mean),
                        ";".join(hashes), str(distinct), worst,
                        decimal_text(Decimal(str(bytes_median))), str(ok_total), "ok"))
    need(len(out) == len(JULIA_STRATA) * CASES, "unexpected number of rows")
    return out


def render(rows):
    buffer = io.StringIO()
    for line in HEADER:
        buffer.write(line + "\n")
    buffer.write("\t".join(COLUMNS) + "\n")
    for row in rows:
        buffer.write("\t".join(row) + "\n")
    return buffer.getvalue()


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("archive_root", help="extracted directory pre06-stage2a-campaign-v1/")
    parser.add_argument("--check", metavar="FILE",
                        help="exit 1 unless FILE equals the regenerated TSV (# lines included)")
    args = parser.parse_args(argv)
    if not os.path.isdir(args.archive_root) or os.path.islink(args.archive_root):
        print(f"ABORT: {args.archive_root} is not a directory (an extracted archive root is required)",
              file=sys.stderr)
        return 2
    try:
        text = render(build_rows(args.archive_root))
    except Abort as err:
        print(f"ABORT: {err}", file=sys.stderr)
        return 2
    except (KeyError, ValueError, OSError, tomllib.TOMLDecodeError) as err:
        print(f"ABORT: unreadable archive ({type(err).__name__}: {err})", file=sys.stderr)
        return 2
    if args.check is None:
        sys.stdout.write(text)
        return 0
    try:
        with open(args.check, newline="", encoding="utf-8") as handle:
            committed = handle.read()
    except OSError as err:
        print(f"CHECK FAILED: cannot read {args.check}: {err}", file=sys.stderr)
        return 1
    if committed == text:
        print(f"CHECK OK: {args.check} equals the regenerated reference "
              f"({len(text.splitlines())} lines)")
        return 0
    old, new = committed.splitlines(), text.splitlines()
    for number, (a, b) in enumerate(zip(old, new), 1):
        if a != b:
            print(f"CHECK FAILED: line {number} differs\n  committed:   {a}\n  regenerated: {b}",
                  file=sys.stderr)
            break
    else:
        print(f"CHECK FAILED: {len(old)} committed lines, {len(new)} regenerated", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
